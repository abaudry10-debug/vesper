// les accents : deux rangées au-dessus de la lettre (la cédille, deux en dessous)
const ACC: Record<string, string[]> = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circ: ['..#..', '.#.#.'],
  diaer: ['.....', '.#.#.'],
};
const ACC3: Record<string, string[]> = { circ: ['.#.', '#.#'], diaer: ['...', '#.#'] };
const DECOMP: Record<string, [string, string]> = {
  É: ['E', 'acute'], È: ['E', 'grave'], Ê: ['E', 'circ'], Ë: ['E', 'diaer'],
  À: ['A', 'grave'], Â: ['A', 'circ'], Î: ['I', 'circ'], Ï: ['I', 'diaer'],
  Ô: ['O', 'circ'], Ù: ['U', 'grave'], Û: ['U', 'circ'], Ü: ['U', 'diaer'], Ç: ['C', 'cedil'],
};
const ALIAS: Record<string, string> = { '’': "'", '‘': "'", '…': '...', 'Œ': 'OE', '—': '-', '–': '-', '×': 'X', ' ': ' ', ' ': ' ' };

const norm = (text: string) => {
  let s = '';
  for (const ch of text.toUpperCase()) s += ALIAS[ch] ?? ch;
  return s;
};
const glyphOf = (ch: string) => G[DECOMP[ch]?.[0] ?? ch] ?? G['?'];

/** Largeur d'un texte, en pixels (à l'échelle S). */
export function pxTextWidth(text: string, S = 1): number {
  let w = 0;
  for (const ch of norm(text)) w += (glyphOf(ch)[0].length + 1) * S;
  return Math.max(0, w - S);
}

/** Hauteur d'une ligne (lettre + place des accents), en pixels à l'échelle S. */
export const PX_LINE = 10;

/** Écrit un texte en pixels ; (x, y) = coin haut-gauche de la lettre (les accents débordent de 2 au-dessus). */
export function pxText(c: CanvasRenderingContext2D, text: string, x: number, y: number, col: string, S = 1) {
  c.fillStyle = col;
  let cx = Math.round(x);
  const y0 = Math.round(y);
  const dot = (gx: number, gy: number) => c.fillRect(cx + gx * S, y0 + gy * S, S, S);
  for (const ch of norm(text)) {
    const g = glyphOf(ch);
    g.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) if (row[gx] === '#') dot(gx, gy);
    });
    const acc = DECOMP[ch]?.[1];
    if (acc === 'cedil') {
      dot(2, 7);
      dot(1, 8);
    } else if (acc) {
      const a = (g[0].length === 3 ? ACC3 : ACC)[acc] ?? ACC[acc];
      a.forEach((row, ay) => {
        for (let gx = 0; gx < row.length; gx++) if (row[gx] === '#') dot(gx, ay - 2);
      });
    }
    cx += (g[0].length + 1) * S;
  }
}

/** Plusieurs lignes, centrées ou non. */
export function pxLines(c: CanvasRenderingContext2D, lines: string[], x: number, y: number, col: string, opts: { S?: number; lh?: number; center?: number } = {}) {
  const S = opts.S ?? 1, lh = opts.lh ?? PX_LINE * S;
  lines.forEach((l, i) => {
    const lx = opts.center !== undefined ? Math.round(opts.center - pxTextWidth(l, S) / 2) : x;
    pxText(c, l, lx, y + i * lh, col, S);
  });
}
